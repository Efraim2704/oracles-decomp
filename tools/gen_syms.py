#!/usr/bin/env python3
"""Generate src/game/syms.h and src/game/syms.c: the per-game address tables behind SYM()/RAMSYM().

usage: tools/gen_syms.py [ages.sym] [seasons.sym] [ages.gbc] [seasons.gbc]
With ref/eu/ages_eu.sym and ref/eu/seasons_eu.sym (tools/eu_sym.py) the European ROMs get columns of
their own: each USA address is carried over to the EU address of the label there, or poisoned when
the label could not be placed. RAM is the same in every region.
Reads src/hooks/syms_used.txt (written by tools/symbolize.py: id, label, Ages bank:addr) and
src/hooks/ram_syms.txt (written by tools/gen_ram.py). A label that a game does not have gets the
poison value 0xffffffff there; a hook that reaches it would burn at address 0xffff in bank 0xff.
Labels with several copies in Ages are paired with Seasons copies by content (symfiles.pair_instances).
"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from symfiles import rom_labels, eu_sym_for, eu_address_map

ages_sym = sys.argv[1] if len(sys.argv) > 1 else 'ref/oracles-disasm/ages.sym'
seasons_sym = sys.argv[2] if len(sys.argv) > 2 else 'ref/oracles-disasm/seasons.sym'
ages, seasons = rom_labels(ages_sym), rom_labels(seasons_sym)
POISON = 0xffffffff

rows = []
missing = []
from symfiles import pair_instances
pairs = pair_instances(sys.argv[3] if len(sys.argv) > 3 else "roms/Legend of Zelda, The - Oracle of Ages (USA, Australia).gbc", ages_sym,
                       sys.argv[4] if len(sys.argv) > 4 else "roms/Legend of Zelda, The - Oracle of Seasons (USA, Australia).gbc", seasons_sym)
for line in open('src/hooks/syms_used.txt'):
    sid, name, ba = line.split()
    if ba == '-':      # a Seasons-only label (TAIL_GV targets): poison in Ages
        s = seasons.get(name, [None])[0]
        if s is None: missing.append(sid)
        rows.append((sid, POISON, POISON if s is None else (s[0] << 16) | s[1]))
        continue
    bank, addr = int(ba[:2], 16), int(ba[3:], 16)
    parent = name.split('@')[0]
    s = pairs.get((name, bank, addr))     # unnamed code pairs only through references (symfiles.pair_instances)
    if s is None: missing.append(sid)
    rows.append((sid, (bank << 16) | addr, POISON if s is None else (s[0] << 16) | s[1]))

# the European ROMs: the same labels at their EU addresses
eu_maps = {}
for game, sym in (('ages', ages_sym), ('seasons', seasons_sym)):
    eu = eu_sym_for(sym)
    eu_maps[game] = eu_address_map(sym, eu) if eu else {}
def eu_of(game, v):
    if v == POISON: return POISON
    e = eu_maps[game].get((v >> 16, v & 0xffff))
    return POISON if e is None else (e[0] << 16) | e[1]
rows = [(sid, a, s, eu_of('ages', a), eu_of('seasons', s)) for sid, a, s in rows]
eu_missing = {g: sum(1 for r in rows if r[c] != POISON and r[c + 2] == POISON) for g, c in (('ages', 1), ('seasons', 2))}

ram = [(cn, int(a[0], 10) << 16 | int(a[2:], 16), int(s[0], 10) << 16 | int(s[2:], 16)) for cn, a, s in (l.split() for l in open('src/hooks/ram_syms.txt'))]

import io, os
h_old = open('src/game/syms.h').read() if os.path.exists('src/game/syms.h') else None
with io.StringIO() as h:
    h.write('// generated by tools/gen_syms.py; do not edit\n#pragma once\n#include <stdint.h>\n')
    h.write('enum {\n')
    for sid, *_ in rows: h.write(f'  S_{sid},\n')
    h.write('  SYM_COUNT\n};\n')
    h.write('enum {\n')
    for cn, _, _ in ram: h.write(f'  R_{cn},\n')
    h.write('  RAMSYM_COUNT\n};\n')
    h.write('extern const uint32_t *game_syms;\nextern const uint32_t *game_ram;\n')
    h.write('#define SYM(l) ((uint16_t)game_syms[S_##l])\n')
    h.write('#define SYMBANK(l) ((uint8_t)(game_syms[S_##l] >> 16))\n')
    h.write('#include "game/ofs.h"\n')
    h.write('#define BASE(l) const uint16_t b_ = SYM(l); const uint8_t bk_ = SYMBANK(l); const uint16_t *om_ = game_seasons ? ofs_for_sym(S_##l) : 0; (void)bk_; (void)om_\n')
    h.write('#define BANKOF(l) const uint8_t bk_ = SYMBANK(l); (void)bk_\n')
    h.write('#define RAMSYM(i) ((uint16_t)game_ram[i])\n')
    h.write('extern int game_seasons;\n#define GV(ages, seasons) (game_seasons ? (seasons) : (ages))\n')
    h.write('// the European ROM of the running game (2 MB, five languages): the same RAM, other ROM addresses\n')
    h.write('extern int game_eu;\n#define RV(us, eu) (game_eu ? (eu) : (us))\n')
    h.write('#define GVW(a, s) (*(game_seasons ? &gb->wram[s##_BANK][(s) & 0xfff] : &gb->wram[a##_BANK][(a) & 0xfff]))\n')
    h.write('#define GVH(a, s) (*(game_seasons ? &gb->hram[(s) - 0xff80] : &gb->hram[(a) - 0xff80]))\n')
    h.write('#define RAMBANK(i) (game_ram[i] >> 16)\n')
    h.write('void syms_select(int seasons, int eu);\n')

    h_new = h.getvalue()
if h_new != h_old:          # an unchanged header keeps its timestamp: every game file includes it
    with open('src/game/syms.h', 'w') as f: f.write(h_new)

with open('src/game/syms.c', 'w') as c:
    c.write('// generated by tools/gen_syms.py; do not edit\n#include "game/syms.h"\n')
    for game, col in (('ages', 1), ('seasons', 2), ('ages_eu', 3), ('seasons_eu', 4)):
        c.write(f'static const uint32_t syms_{game}[SYM_COUNT] = {{\n')
        for row in rows: c.write(f'  0x{row[col]:08x},\n')
        c.write('};\n')
    for game, col in (('ages', 1), ('seasons', 2)):
        c.write(f'static const uint32_t ram_{game}[RAMSYM_COUNT] = {{\n')
        for r in ram: c.write(f'  0x{r[col]:08x},\n')
        c.write('};\n')
    c.write('const uint32_t *game_syms = syms_ages;\nconst uint32_t *game_ram = ram_ages;\n')
    c.write('int game_seasons, game_eu;\n')
    c.write('void syms_select(int seasons, int eu) {\n')
    c.write('  game_seasons = seasons; game_eu = eu;\n')
    c.write('  game_syms = seasons ? (eu ? syms_seasons_eu : syms_seasons) : (eu ? syms_ages_eu : syms_ages);\n')
    c.write('  game_ram = seasons ? ram_seasons : ram_ages;\n}\n')

print(f'{len(rows)} ROM symbols ({len(missing)} missing in Seasons; not placed in EU: {eu_missing["ages"]} Ages, {eu_missing["seasons"]} Seasons), {len(ram)} per-game RAM symbols')
